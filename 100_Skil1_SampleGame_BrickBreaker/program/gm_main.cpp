#include <time.h>                  // 時間取得のための標準ライブラリ
#include <string>                  // 文字列を扱うための標準ライブラリ
#include <dxe.h>                   // DXE ライブラリ (ゲーム用描画・入力補助)
#include "../ResourceConstantHedder.h"
#include "gm_main.h"               // このファイルのヘッダ
#include "scene_title.h"          // タイトルシーン
#include "scene_in_game.h"        // ゲームプレイシーン
#include "scene_result.h"         // リザルトシーン

// 現在のシーンを管理するグローバル変数（初期値：タイトル初期化）
int g_scene_id = SCENE_TITLE_INIT;

//------------------------------------------------------------------------------------------------------------
// ゲーム起動時に１度だけ実行される初期化処理（ランダムシードの初期化）
//------------------------------------------------------------------------------------------------------------
void gameStart() {
	srand(time(0));  // 現在時刻をシードに乱数初期化
}

//------------------------------------------------------------------------------------------------------------
// 毎フレーム呼び出されるメイン関数（シーンの遷移と処理を管理）
// delta_time : 前フレームからの経過時間（秒）
//------------------------------------------------------------------------------------------------------------
void gameMain(float delta_time) {

	// シーン初期化処理（IDに _INIT が付く状態で実行される）
	switch (g_scene_id) {
	case SCENE_TITLE_INIT:
		sceneTitleInitialize();       // タイトルシーン初期化
		g_scene_id = SCENE_TITLE;     // 次の処理対象をタイトルに
		break;

	case SCENE_IN_GAME_INIT:
		sceneInGameInitialize();      // ゲームプレイシーン初期化
		g_scene_id = SCENE_IN_GAME;
		break;

	case SCENE_RESULT_INIT:
		sceneResultInitialize();      // リザルトシーン初期化
		g_scene_id = SCENE_RESULT;
		break;
	}

	// 現在のシーンに応じた処理実行（毎フレーム呼び出し）
	switch (g_scene_id) {
	case SCENE_TITLE:
		g_scene_id = sceneTitleProcess();    // タイトルシーンのロジックを実行し、次のシーンIDを返す
		break;

	case SCENE_IN_GAME:
		g_scene_id = sceneInGameProcess();   // プレイ中の処理
		break;

	case SCENE_RESULT:
		g_scene_id = sceneResultProcess();   // リザルト画面処理
		break;
	}

	// 画面左下にFPSインジケーターを描画
	dxe::DrawFpsIndicator({ 10, DXE_WINDOW_HEIGHT - 10 });
}

