#pragma once
#include <dxe.h>

//--------------------------------------------------------------------------------------------------------------------------
// Block クラス
// ブロック崩しゲームに登場するブロックの定義。
// 位置・サイズ・生存状態を管理し、描画や初期化を行う。
//--------------------------------------------------------------------------------------------------------------------------
class Block {
public:

	// ブロックのサイズ（幅と高さ）
	tnl::Vector2f size_;

	// ブロックの位置（画面上の座標）
	tnl::Vector2f position_;

	// ブロックが生存しているかどうかのフラグ（false の場合は消滅済み）
	bool is_alive_ = true;

	// ブロックの画像ハンドル
	int image_handle_ = 0;

	// 初期化処理：位置とサイズを設定し、ブロックを生存状態にする
	void initialize(tnl::Vector2f position, tnl::Vector2f size, int image_handle);

	// 更新処理：現在は未使用。将来的な拡張のために定義
	void update();

	// 描画処理：ブロックを画面に描画する（生存状態のブロックのみ）
	void draw();
};