#pragma once
#include <dxe.h>

//--------------------------------------------------------------------------------------------------------------------------
// Bar クラス
// プレイヤーが操作するバーのクラス。位置、サイズ、描画、更新処理を管理。
//--------------------------------------------------------------------------------------------------------------------------
class Bar {
public:

	// バーのサイズ（横140, 縦30）画像サイズ
	const tnl::Vector2f size_ = { 140.0f, 30.0f };

	// バーの現在位置（画面上の座標）
	tnl::Vector2f position_;

	// バーの画像ハンドル
	int image_handle_ = 0;

	// 初期化処理（バーの初期位置を設定）
	void initialize( int image_handle );

	// 更新処理（入力に応じてバーを左右に移動）
	void update();

	// 描画処理（バーを画面に描画）
	void draw();
};
