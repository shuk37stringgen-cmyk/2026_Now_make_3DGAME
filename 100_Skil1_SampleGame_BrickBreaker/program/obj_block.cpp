#include "obj_block.h"

//--------------------------------------------------------------------------------------------------------------------------
// Block クラスの初期化処理
// 位置とサイズを指定してブロックを初期化し、表示状態を「生存」に設定する。
//--------------------------------------------------------------------------------------------------------------------------
void Block::initialize(tnl::Vector2f position, tnl::Vector2f size, int image_handle) {
	size_ = size;					// ブロックのサイズを設定
	position_ = position;			// ブロックの位置を設定
	is_alive_ = true;				// ブロックを「生きている」状態にする
	image_handle_ = image_handle;	// ブロックの画像ハンドルを設定
}

