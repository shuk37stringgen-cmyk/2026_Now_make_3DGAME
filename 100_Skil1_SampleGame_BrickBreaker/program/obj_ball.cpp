#include "obj_ball.h"

//--------------------------------------------------------------------------------------------------------------------------
// ボールの初期化処理
// 位置を画面中央やや下に設定し、移動方向を右下に初期化する
//--------------------------------------------------------------------------------------------------------------------------
void Ball::initialize() {
	move_dir_ = { speed_, speed_ };                  // 速度に基づいて移動方向を右下に設定
	position_ = { DXE_WINDOW_WIDTH_HALF, 400.0f };   // ボールの初期位置（画面中央の少し下）
}

//--------------------------------------------------------------------------------------------------------------------------
// ボールの更新処理
// 位置の更新、壁との反射処理を行う
//--------------------------------------------------------------------------------------------------------------------------
void Ball::update() {
	before_position_ = position_;   // 前のフレームの位置を記録（衝突判定などに使用）
	position_ += move_dir_;         // 現在の移動方向に基づいて位置を更新
}

//--------------------------------------------------------------------------------------------------------------------------
// ボールの描画処理
// 現在位置に四角形でボールを描画する
//--------------------------------------------------------------------------------------------------------------------------
void Ball::draw() {
	dxe::DrawBox(position_, radius_, radius_, false, dxe::Colors::DeepPink);  // 四角形（線のみ）で描画
}
