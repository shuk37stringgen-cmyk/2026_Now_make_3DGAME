#pragma once
#include <dxe.h>

//--------------------------------------------------------------------------------------------------------------------------
// Ballクラス
// プレイヤーが操作しない自動移動するボールオブジェクト。
// 画面内を反射しながら移動し、バーやブロックとの衝突処理に関わる。
//--------------------------------------------------------------------------------------------------------------------------
class Ball {
public:

	const float radius_ = 20.0f;          // ボールの半径（衝突判定や描画に使用）
	tnl::Vector2f before_position_;       // 1フレーム前の位置（衝突補正時に使用）
	tnl::Vector2f position_;              // 現在の位置
	tnl::Vector2f move_dir_;              // 移動方向ベクトル（単位にspeed_が乗算されて使われる）
	float speed_ = 3.0f;                  // 移動速度（ピクセル毎フレーム）
	bool is_move_ = false;                // ボールが移動中かどうか（未使用なら将来的な機能追加用）


	// 初期化処理（位置と移動方向を設定）
	void initialize();

	// 更新処理（位置更新・壁反射）
	void update();

	// 描画処理（現在位置にボールを描画）
	void draw();
};
